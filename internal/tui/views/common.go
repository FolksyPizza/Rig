package views

type BackMsg struct{}

// truncate shortens s to at most max display cells, counting runes rather than
// bytes so multi-byte output is not cut mid-character.
func truncate(s string, max int) string {
	if max <= 0 {
		return ""
	}
	runes := []rune(s)
	if len(runes) <= max {
		return s
	}
	if max <= 3 {
		return string(runes[:max])
	}
	return string(runes[:max-3]) + "..."
}
